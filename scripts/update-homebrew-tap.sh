#!/usr/bin/env bash
# Points the Homebrew formula (dcode-co/homebrew-tap, Formula/kc.rb) at a
# published release, using the checksums in its SHA256SUMS, and pushes it.
#
#   scripts/update-homebrew-tap.sh v0.1.0
#
# Needs `gh` logged in with write access to the tap. Run it after the release
# is published (scripts/release-sign-macos.sh --publish does that for you).
#
#   KC_REPO  [default: dcode-co/1pass-keychain]
#   KC_TAP   [default: dcode-co/homebrew-tap]
set -euo pipefail

tag=${1:?usage: $0 vX.Y.Z}
repo=${KC_REPO:-dcode-co/1pass-keychain}
tap=${KC_TAP:-dcode-co/homebrew-tap}
version=${tag#v}

if [ "$(gh release view "$tag" --repo "$repo" --json isDraft --jq .isDraft)" != false ]; then
  echo "$tag is not a published release; the formula would point at missing files" >&2
  exit 1
fi

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
gh release download "$tag" --repo "$repo" --pattern SHA256SUMS --dir "$work"

sum() {
  local file="kc-$tag-$1.tar.gz" hash
  hash=$(awk -v f="$file" '$2 == f { print $1 }' "$work/SHA256SUMS")
  [ -n "$hash" ] || { echo "SHA256SUMS has no $file" >&2; exit 1; }
  echo "$hash"
}
mac_arm=$(sum aarch64-apple-darwin)
mac_intel=$(sum x86_64-apple-darwin)
linux_arm=$(sum aarch64-unknown-linux-musl)
linux_intel=$(sum x86_64-unknown-linux-musl)
base="https://github.com/$repo/releases/download/$tag"

gh repo clone "$tap" "$work/tap" -- --quiet
mkdir -p "$work/tap/Formula"
cat > "$work/tap/Formula/kc.rb" <<EOF
# Generated by scripts/update-homebrew-tap.sh in $repo. Don't edit by hand.
class Kc < Formula
  desc "Move secrets between your own devices' OS keychains"
  homepage "https://github.com/$repo"
  version "$version"
  license "MIT"

  on_macos do
    on_arm do
      url "$base/kc-$tag-aarch64-apple-darwin.tar.gz"
      sha256 "$mac_arm"
    end
    on_intel do
      url "$base/kc-$tag-x86_64-apple-darwin.tar.gz"
      sha256 "$mac_intel"
    end
  end

  on_linux do
    on_arm do
      url "$base/kc-$tag-aarch64-unknown-linux-musl.tar.gz"
      sha256 "$linux_arm"
    end
    on_intel do
      url "$base/kc-$tag-x86_64-unknown-linux-musl.tar.gz"
      sha256 "$linux_intel"
    end
  end

  def install
    bin.install "kc"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/kc --version")
  end
end
EOF

cd "$work/tap"
git add Formula/kc.rb
if git diff --cached --quiet; then
  echo "Formula/kc.rb already points at $tag"
  exit 0
fi
git commit --quiet -m "kc $version"
git push --quiet origin HEAD:main
echo "pushed Formula/kc.rb for $tag to $tap"
